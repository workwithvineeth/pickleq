/**
 * STAGING ONLY: builds the SQL that fills the paddleq-staging database with the same fictional data the on-phone demo
 * shows (PQ Demo Club, its finished and live tournaments with point-by-point scores, the events board, other clubs,
 * tournaments waiting for approval, registrations), plus what the demo can't show: test accounts for each role,
 * a claimable player for Player Studio, scorer links with a referee PIN, a desk link with a desk PIN, and a Studio diary.
 *
 * Usage (CI job staging-db): node dist-staging/seed.mjs > seed.sql. Accounts are made first by the staging-setup
 * function; this SQL finds them by email. Every name and email is made up (…@example.com never receives mail).
 * Running it again replaces the earlier demo data.
 */
import { DemoBackend } from '../../src/club/demo';
import { formatJson } from '../../src/club/server';
import type { Club, ClubMatch, ClubPlayer, ClubTournament, Division, Entry, Registration } from '../../src/club/types';

export const ACCOUNTS = {
  organiser: { email: 'organiser@example.com', name: 'Vineeth (organiser)' },
  admin: { email: 'admin@example.com', name: 'PaddleQ Admin' },
  player: { email: 'player@example.com', name: 'Kabir Rao' },
  member: { email: 'member@example.com', name: 'Diya Menon' },
} as const;
export const REFEREE_PIN = '4826';
export const DESK_PIN = '739158';

class Mem {
  private m = new Map<string, string>();
  get length() { return this.m.size; }
  clear() { this.m.clear(); }
  getItem(k: string) { return this.m.get(k) ?? null; }
  key(i: number) { return [...this.m.keys()][i] ?? null; }
  removeItem(k: string) { this.m.delete(k); }
  setItem(k: string, v: string) { this.m.set(k, String(v)); }
}

const q = (v: unknown): string => {
  if (v === null || v === undefined || v === '') return 'null';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'object') return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const uuidArr = (xs: string[]) => `array[${xs.map((x) => `${q(x)}::uuid`).join(',')}]::uuid[]`;
const isUuid = (x?: string) => !!x && /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(x);
const STAGING_URL = 'https://xlviuobtfszwfmnwcjjr.supabase.co';
/** Inline SVG posters and logos from the demo, to be rendered to PNG and uploaded to the posters bucket by the CI job. */
export const images: { path: string; svg: string }[] = [];
const img = (dataUrl?: string): string | undefined => {
  if (!dataUrl) return undefined;
  if (!dataUrl.startsWith('data:image/svg+xml')) return dataUrl.startsWith('https://') ? dataUrl : undefined;
  const svg = decodeURIComponent(dataUrl.slice(dataUrl.indexOf(',') + 1));
  let h = 0; for (let i = 0; i < svg.length; i++) h = (h * 31 + svg.charCodeAt(i)) >>> 0;
  const path = `staging/${h.toString(16)}.png`;
  if (!images.some((x) => x.path === path)) images.push({ path, svg });
  return `${STAGING_URL}/storage/v1/object/public/posters/${path}`;
};
const uid = (email: string) => `(select id from auth.users where email = ${q(email)})`;
const insert = (table: string, rows: Record<string, string>[]) => rows.length
  ? `insert into public.${table} (${Object.keys(rows[0]).join(', ')}) values\n${rows.map((r) => `  (${Object.values(r).join(', ')})`).join(',\n')};\n`
  : '';

export async function buildSeedSql(today = new Date()): Promise<string> {
  const demo = new DemoBackend(new Mem() as unknown as Storage);
  await demo.start('Vineeth');
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const s = (demo as any).s as { clubs: Club[]; players: ClubPlayer[]; tournaments: ClubTournament[]; divisions: Division[]; entries: Entry[]; matches: ClubMatch[]; registrations: Registration[] };
  void today;
  const home = s.clubs.find((c) => c.name === 'PQ Demo Club')!;
  const out: string[] = ['-- PaddleQ staging demo data (fictional). Generated by scripts/staging/seed.ts.\n'];

  // Start clean: removing the demo clubs removes everything under them.
  out.push(`delete from public.clubs where name like 'PQ Demo %';\n`);
  out.push(`delete from public.platform_admins where user_id in (select id from auth.users where email like '%@example.com');\n`);
  out.push(`delete from public.player_studio_logs where owner_id = ${uid(ACCOUNTS.player.email)};\n`);
  out.push(`delete from public.player_studio_sessions where owner_id = ${uid(ACCOUNTS.player.email)};\n`);

  // Profiles for the test accounts.
  out.push(insert('profiles', Object.values(ACCOUNTS).map((a) => ({ id: uid(a.email), display_name: q(a.name) }))).replace(/;\n$/, ' on conflict (id) do update set display_name = excluded.display_name;\n'));

  out.push(insert('clubs', s.clubs.map((c) => ({
    id: q(c.id), name: q(c.name), city: q(c.city ?? (c.id === home.id ? 'Hyderabad' : null)), invite_code: q(c.inviteCode), settings: q(c.settings ?? {}),
    created_by: c.id === home.id ? uid(ACCOUNTS.organiser.email) : 'null', logo_url: q(img(c.logoUrl)), verified: q(!!c.verified || c.id === home.id),
    trusted: q(c.id === home.id ? true : !!c.trusted), hosting_phone: q(c.hostingPhone), hosting_note: q(c.hostingNote),
  }))));

  // Members: the organiser owns PQ Demo Club; a plain member account sees the member view.
  out.push(insert('club_members', [
    { club_id: q(home.id), user_id: uid(ACCOUNTS.organiser.email), role: q('owner') },
    { club_id: q(home.id), user_id: uid(ACCOUNTS.member.email), role: q('player') },
  ]));
  out.push(insert('club_contacts', [{ club_id: q(home.id), phone: q('+91 90000 11111'), note: q('Fictional number for staging') }]).replace(/;\n$/, ' on conflict do nothing;\n'));

  // Roster. The owner's own player ("Vineeth") is linked to the organiser account; everyone else is unclaimed.
  const homePlayers = s.players.filter((p) => p.clubId === home.id);
  // The claimable player is someone who played in a finished tournament, so the claim shows real matches.
  const doneT = new Set(s.tournaments.filter((t) => t.clubId === home.id && t.status === 'done').map((t) => t.id));
  const played = new Map<string, number>();
  for (const m of s.matches) if (m.tournamentId && doneT.has(m.tournamentId) && m.status === 'done') for (const p of [...m.sideA, ...m.sideB]) played.set(p, (played.get(p) ?? 0) + 1);
  const claimable = homePlayers.filter((p) => !p.userId && played.has(p.id)).sort((a, b) => (played.get(b.id) ?? 0) - (played.get(a.id) ?? 0))[0] ?? homePlayers[5];
  out.push(insert('club_players', s.players.map((p) => ({
    id: q(p.id), club_id: q(p.clubId), name: q(p.name === ACCOUNTS.player.name || p.id !== claimable.id ? p.name : ACCOUNTS.player.name),
    dupr_singles: q(p.duprSingles), dupr_doubles: q(p.duprDoubles), dupr_id: q(p.duprId),
    user_id: p.userId && !isUuid(p.userId) && p.clubId === home.id ? uid(ACCOUNTS.organiser.email) : 'null',
    claimed_at: p.userId && !isUuid(p.userId) && p.clubId === home.id ? 'now()' : 'null', share: q(p.share ?? {}), sample: 'false',
  }))));
  // Fake emails for the roster (so "Send players their results" has something to show). The claimable player's email
  // is the player test account's, so Player Studio finds them after sign-in.
  const slug = (n: string) => n.toLowerCase().replace(/[^a-z]+/g, '.').replace(/^\.|\.$/g, '');
  out.push(insert('club_player_emails', homePlayers.filter((p) => !p.userId).map((p, i) => ({
    player_id: q(p.id), club_id: q(home.id), email: q(p.id === claimable.id ? ACCOUNTS.player.email : `${slug(p.name)}.${i}@example.com`),
  }))));

  out.push(insert('tournaments', s.tournaments.map((t) => ({
    id: q(t.id), club_id: q(t.clubId), name: q(t.name), start_date: q(t.startDate), start_time: q(t.startTime), courts: q(t.courts), slot_minutes: q(t.slotMinutes),
    status: q(t.status), is_public: q(t.isPublic), public_slug: q(t.publicSlug), city: q(t.city), venue: q(t.venue), about: q(t.about), contact: q(t.contact), link: q(t.link),
    entry_mode: q(t.entryMode ?? 'roster'), registration_open: q(!!t.registrationOpen), entries_close: q(t.entriesClose), upi_id: q(t.upiId),
    listing: q(t.listing ?? 'none'), listing_status: q(t.listingStatus ?? 'none'), reject_reason: q(t.rejectReason), reviewed_at: q(t.reviewedAt), drawn_at: q(t.drawnAt),
    poster_url: q(img(t.posterUrl)), approval: q(t.approval ?? 'approved'), approval_reason: q(t.approvalReason), approval_requested_at: q(t.approvalRequestedAt),
    approval_expected: q(t.approvalExpected), created_by: t.clubId === home.id ? uid(ACCOUNTS.organiser.email) : 'null',
  }))));

  out.push(insert('divisions', s.divisions.map((d) => ({
    id: q(d.id), tournament_id: q(d.tournamentId), club_id: q(d.clubId), name: q(d.name), kind: q(d.kind), format: q(formatJson(d)), pools: q(d.pools), advance: q(d.advance),
    sort: q(d.sort ?? 0), max_dupr: q(d.rules?.maxDupr), dupr_cap: q(d.rules?.duprCap === 'average' ? 'average' : 'each'), gender: q(d.rules?.gender ?? 'open'),
    min_age: q(d.rules?.minAge), cap: q(d.rules?.cap), fee: q(d.rules?.fee),
  }))));

  out.push(insert('entries', s.entries.map((e) => ({
    id: q(e.id), division_id: q(e.divisionId), club_id: q(e.clubId), player_ids: uuidArr(e.playerIds), seed: q(e.seed), pool: q(e.pool), status: q(e.status ?? 'active'),
  }))));

  const matchRows = s.matches.map((m) => ({
    id: q(m.id), club_id: q(m.clubId), tournament_id: q(m.tournamentId), division_id: q(m.divisionId), stage: q(m.stage), pool: q(m.pool), round: q(m.round),
    bracket_pos: q(m.bracketPos), slot: q(m.slot), court: q(m.court), entry_a: q(m.entryA), entry_b: q(m.entryB), side_a: uuidArr(m.sideA), side_b: uuidArr(m.sideB),
    format: q(m.format), games: q(m.games ?? []), status: q(m.status), winner: q(m.winner), played_on: q(m.playedOn),
  }));
  for (let i = 0; i < matchRows.length; i += 200) out.push(insert('club_matches', matchRows.slice(i, i + 200)));

  out.push(insert('registrations', (s.registrations ?? []).map((r) => ({
    id: q(r.id), tournament_id: q(r.tournamentId), division_id: q(r.divisionId), club_id: q(r.clubId), user_id: 'null', source: q(r.source),
    players: q(r.players.map((p, i) => ({ ...p, email: p.email ?? `${slug(p.name)}.r${i}@example.com` }))), status: q(r.status), payment: q(r.payment),
    payment_ref: q(r.paymentRef), note: q(r.note), entry_id: q(r.entryId),
  }))));

  // Referee and desk access for every live or upcoming tournament of PQ Demo Club.
  const ownT = s.tournaments.filter((t) => t.clubId === home.id && t.status !== 'done');
  for (const t of ownT) {
    // A trigger makes these when a tournament is added; set known PINs so the walkthrough can list them.
    out.push(insert('tournament_pins', [{ tournament_id: q(t.id), club_id: q(home.id), pin: q(REFEREE_PIN) }]).replace(/;\n$/, ' on conflict (tournament_id) do update set pin = excluded.pin;\n'));
    out.push(insert('tournament_desks', [{ tournament_id: q(t.id), club_id: q(home.id), pin: q(DESK_PIN) }]).replace(/;\n$/, ' on conflict (tournament_id) do update set pin = excluded.pin;\n'));
    out.push(insert('scorer_links', Array.from({ length: t.courts }, (_, i) => ({ tournament_id: q(t.id), club_id: q(home.id), court: q(i + 1), label: q(`Court ${i + 1}`) }))));
  }

  // PaddleQ admin.
  out.push(`insert into public.platform_admins (user_id) select ${uid(ACCOUNTS.admin.email)} on conflict do nothing;\n`);

  // A Player Studio diary for the player account (casual matches and practice), so Stats and Coach have something to show.
  const day = (n: number) => { const d = new Date(); d.setDate(d.getDate() - n); return d.toISOString().slice(0, 10); };
  const logs = [
    [3, 'doubles', 'Aarav S. & Riya K.', 'Meera N.', 11, 7, 'Dinks were patient; won most kitchen exchanges.'],
    [6, 'doubles', 'Rohan G. & Tara B.', 'Meera N.', 9, 11, 'Missed too many third-shot drops into the net.'],
    [9, 'singles', 'Ishaan P.', null, 11, 8, 'Deep returns kept him back.'],
    [12, 'doubles', 'Kavya J. & Dev M.', 'Arjun V.', 11, 9, 'Came back from 4–9 with steady resets.'],
    [16, 'singles', 'Varun S.', null, 6, 11, 'Served short under pressure.'],
    [20, 'doubles', 'Nisha D. & Om P.', 'Meera N.', 11, 4, 'Good stacking on serve.'],
    [24, 'doubles', 'Zoya K. & Yash R.', 'Arjun V.', 10, 12, 'Lost the golden point on a lob.'],
    [29, 'singles', 'Ishaan P.', null, 11, 9, 'Passing shots down the line worked.'],
  ] as const;
  out.push(insert('player_studio_logs', logs.map(([n, kind, opp, partner, f, a, note]) => ({
    owner_id: uid(ACCOUNTS.player.email), kind: q('casual'), match_type: q(kind), played_on: q(day(n)), opponents: q(opp), partner: partner ? q(partner) : "''", location: q('PQ Demo Club courts'),
    score_for: q(f), score_against: q(a), reflection: q(note), games: q([{ you: f, them: a }]), setting: q(n % 2 ? 'outdoor' : 'indoor'),
    opponent_strength: q(f > a ? 'equal' : 'stronger'), energy: q(3 + (n % 3)),
  }))));
  const sessions = [[2, 60, 3], [5, 45, 4], [8, 90, 3], [13, 60, 2], [19, 75, 4], [26, 50, 3]] as const;
  out.push(insert('player_studio_sessions', sessions.map(([n, mins, inten]) => ({
    owner_id: uid(ACCOUNTS.player.email), session_on: q(day(n)), kind: q(n % 3 ? 'solo' : 'partner'), minutes: q(mins), intensity: q(inten),
    drills: q([{ category: 'Third-shot drop', made: 14 + n % 7, attempts: 25 }, { category: 'Dink', made: 30 + n % 9, attempts: 40 }, { category: 'Serve', made: 18 + n % 3, attempts: 20 }]),
    ratings: q({ Dink: 3 + (n % 2), Drop: 3, Serve: 4 }), note: q('Drill session'),
  }))));

  out.push(`select ${q(claimable.id)} as claimable_player;\n`);
  return out.join('\n');
}

if (process.argv[1]?.includes('seed')) buildSeedSql().then(async (sql) => {
  process.stdout.write(sql);
  if (process.env.SEED_IMAGES) (await import('node:fs')).writeFileSync(process.env.SEED_IMAGES, JSON.stringify(images));
}).catch((e) => { console.error(e); process.exit(1); });
